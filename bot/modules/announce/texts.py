def get_random_quote(tier: str) -> str:
    """انتخاب تصادفی یک جمله انگیزشی متناسب با رده نظامی."""
    quotes = MOTIVATIONAL_QUOTES.get(tier, MOTIVATIONAL_QUOTES["سرباز"])
    return random.choice(quotes)


def promotion_announcement_text(
    full_name: str,
    telegram_id: int,
    old_rank: Rank,
    new_rank: Rank,
    reason: str | None = None,
    is_legendary: bool = False,
) -> str:
    """قالب ابلاغیه رسمی ترفیع مقام در گروه."""
    quote = get_random_quote(new_rank.tier)
    u_link = user_link(telegram_id, full_name)

    if is_legendary or new_rank.level >= 20:
        # قالب ویژه افسانه‌ای برای سپهبد و ارتشبد
        return (
            f"👑⚡️💎 <b>فرمان فوق‌العاده و حماسی ارتقای درجه</b> 💎⚡️👑\n"
            f"{DIVIDER}\n"
            f"به حکم فرماندهی عالی و با تایید شورای کل قوای ارتش زمین:\n\n"
            f"🎖 <b>مجاهد سرافراز:</b> {u_link}\n"
            f"🔻 از مقام: {old_rank.name_fa} ({old_rank.insignia})\n"
            f"🔺 به بالاترین درجه افتخار: <b>{new_rank.name_fa}</b> ({new_rank.insignia})\n\n"
            f"📜 <i>«{quote}»</i>\n"
            f"{DIVIDER}\n"
            f"{(f'📋 دلیل افتخار: <i>' + clean_html(reason) + '</i>\n' + DIVIDER) if reason else ''}"
            f"🏆 تمام ارتش به احترام فرمانده عالی خبردار می‌ایستد! 🫡"
        )

    # قالب استاندارد نظامی-رسمی
    return (
        f"🎖 <b>ابلاغیه رسمی ترفیع درجه نظامی</b>\n"
        f"{DIVIDER}\n"
        f"با تایید ستاد فرماندهی، ترفیع درجه زیر به تصویب رسید:\n\n"
        f"👤 رزمنده گرامی: {u_link}\n"
        f"📉 از مقام: <b>{old_rank.name_fa}</b> ({old_rank.insignia})\n"
        f"📈 به مقام: <b>{new_rank.name_fa}</b> ({new_rank.insignia})\n"
        f"🏅 رده نظامی: <b>{new_rank.tier}</b>\n\n"
        f"💬 <i>«{quote}»</i>\n"
        f"{DIVIDER}\n"
        f"{(f'📋 دلیل ترفیع: <i>' + clean_html(reason) + '</i>\n' + DIVIDER) if reason else ''}"
        f"✨ این پیروزی و پیشرفت را تبریک می‌گوییم! 🫡"
    )


def season_summary_text(
    promoted_count: int,
    capped_count: int,
    total_players: int,
    tier_counts: dict[str, int],
) -> str:
    """متن گزارش خلاصه پایان فصل (ارسال تجمیعی یکباره)."""
    lines = [
        header("گزارش رسمی ستاد کل در پایان فصل بازی زمین", "🌍"),
        f"👥 کل بازیکنان غیور این فصل: {bold(fa_number(total_players))}",
        f"📈 تعداد ترفیع‌یافتگان: {bold(fa_number(promoted_count))} رزمنده",
        f"🔒 رزمندگان شایسته در سقف خودکار (سرهنگ): {bold(fa_number(capped_count))} نفر",
        DIVIDER,
        "📊 <b>آمار رده‌های نظامی در این فصل:</b>",
    ]
    for tier_name, count in tier_counts.items():
        if count > 0:
            lines.append(f"▪️ {tier_name}: {bold(fa_number(count))} نفر")

    lines.append(DIVIDER)
    lines.append("🫡 درود بر رزمندگان و رهبرانی که نام میهن خود را جاودانه ساختند!")
    return "\n".join(lines)
